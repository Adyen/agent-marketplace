// catalog-docs generates site/docs/reference/hook-and-tool-names.md from the
// toolpolicy and hookpolicy catalogs, or verifies it is current with -check.
// It runs offline: inputs are only the YAML files shipped in the repository.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	toolDir   = "pkg/harness-compilation/toolpolicy"
	hookDir   = "pkg/harness-compilation/hookpolicy"
	docPath   = "site/docs/reference/hook-and-tool-names.md"
	generated = "<!-- Generated by `make catalog-docs` (tools/catalog-docs); do not edit. -->"
)

type evidence struct {
	Checked string   `yaml:"checked"`
	Refs    []string `yaml:"refs"`
	Notes   string   `yaml:"notes"`
}

type concepts struct {
	Tools  map[string]string `yaml:"tools"`
	Events map[string]string `yaml:"events"`
}

type toolCatalog struct {
	Harness  string   `yaml:"harness"`
	Evidence evidence `yaml:"evidence"`
	MCP      struct {
		Pattern      string `yaml:"pattern"`
		All          string `yaml:"all"`
		ServerScoped bool   `yaml:"server_scoped"`
	} `yaml:"mcp"`
	Surfaces []string `yaml:"surfaces"`
	Tools    map[string]struct {
		Concepts []string `yaml:"concepts"`
		Aliases  []string `yaml:"aliases"`
		Surfaces []string `yaml:"surfaces"`
	} `yaml:"tools"`
}

type envVar struct {
	Names  []string `yaml:"names"`
	Events []string `yaml:"events"`
}

func (v *envVar) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind == yaml.SequenceNode {
		return node.Decode(&v.Names)
	}
	type plain envVar
	return node.Decode((*plain)(v))
}

type hookCatalog struct {
	Harness        string            `yaml:"harness"`
	Evidence       evidence          `yaml:"evidence"`
	Env            map[string]envVar `yaml:"env"`
	PluginEnv      map[string]envVar `yaml:"plugin_env"`
	RepositoryBase *struct {
		Env   string `yaml:"env"`
		Shell string `yaml:"shell"`
		Cwd   string `yaml:"cwd"`
	} `yaml:"repository_base"`
	Timeout struct {
		Unit string `yaml:"unit"`
	} `yaml:"timeout"`
	Matcher struct {
		Syntax     string `yaml:"syntax"`
		Anchor     bool   `yaml:"anchor"`
		ExactLists bool   `yaml:"exact_lists"`
	} `yaml:"matcher"`
	LoadsHooksOf []string `yaml:"loads_hooks_of"`
	Events       map[string]struct {
		Canonical string   `yaml:"canonical"`
		Matcher   string   `yaml:"matcher"`
		Types     []string `yaml:"types"`
		Timeout   *struct {
			Min int `yaml:"min"`
			Max int `yaml:"max"`
		} `yaml:"timeout"`
		Tools []string `yaml:"tools"`
		MCP   bool     `yaml:"mcp"`
	} `yaml:"events"`
}

func load[T any](path string) (T, error) {
	var out T
	raw, err := os.ReadFile(path)
	if err != nil {
		return out, err
	}
	return out, yaml.Unmarshal(raw, &out)
}

func table(buf *bytes.Buffer, header []string, rows [][]string) {
	buf.WriteString("| " + strings.Join(header, " | ") + " |\n")
	buf.WriteString("|" + strings.Repeat(" --- |", len(header)) + "\n")
	for _, row := range rows {
		buf.WriteString("| " + strings.Join(row, " | ") + " |\n")
	}
	buf.WriteString("\n")
}

func joinOr(parts []string, empty string) string {
	if len(parts) == 0 {
		return empty
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func generate() ([]byte, error) {
	vocab, err := load[concepts](filepath.Join(toolDir, "concepts.yaml"))
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(generated + "\n\n")
	buf.WriteString("# Hook and tool names\n\n")
	buf.WriteString("The tool names, hook events, environment variables, and contract details " +
		"each harness uses, generated from the shipped catalogs in " +
		"`pkg/harness-compilation/toolpolicy` and `pkg/harness-compilation/hookpolicy`. " +
		"Regenerate with `make catalog-docs`; `make catalog-check` fails when this page is stale.\n\n")

	buf.WriteString("## Shared tool concepts\n\n")
	rows := [][]string{}
	for _, name := range sortedKeys(vocab.Tools) {
		rows = append(rows, []string{"`" + name + "`", vocab.Tools[name]})
	}
	table(&buf, []string{"Concept", "Meaning"}, rows)

	buf.WriteString("## Canonical hook events\n\n")
	rows = [][]string{}
	for _, name := range sortedKeys(vocab.Events) {
		rows = append(rows, []string{"`" + name + "`", vocab.Events[name]})
	}
	table(&buf, []string{"Canonical event", "Meaning"}, rows)

	buf.WriteString("## Tool names by harness\n\n")
	toolEntries, err := filepath.Glob(filepath.Join(toolDir, "catalogs", "*.yaml"))
	if err != nil {
		return nil, err
	}
	for _, file := range toolEntries {
		c, err := load[toolCatalog](file)
		if err != nil {
			return nil, err
		}
		buf.WriteString("### " + c.Harness + "\n\n")
		buf.WriteString("Surfaces: " + joinOr(c.Surfaces, "none") + ". MCP naming: `" + c.MCP.Pattern +
			"`; match-all `" + c.MCP.All + "`; server scoped: " + fmt.Sprint(c.MCP.ServerScoped) + ".\n\n")
		if len(c.Tools) == 0 {
			buf.WriteString("No tool-name vocabulary: tool selection is encoded in the hook event.\n\n")
			continue
		}
		rows := [][]string{}
		for _, name := range sortedKeys(c.Tools) {
			t := c.Tools[name]
			rows = append(rows, []string{
				"`" + name + "`",
				joinOr(t.Concepts, "-"),
				joinOr(t.Aliases, "-"),
				joinOr(t.Surfaces, "all"),
			})
		}
		table(&buf, []string{"Tool", "Concepts", "Aliases", "Surfaces"}, rows)
	}

	buf.WriteString("## Hook contracts by harness\n\n")
	hookEntries, err := filepath.Glob(filepath.Join(hookDir, "catalogs", "*.yaml"))
	if err != nil {
		return nil, err
	}
	for _, file := range hookEntries {
		c, err := load[hookCatalog](file)
		if err != nil {
			return nil, err
		}
		buf.WriteString("### " + c.Harness + "\n\n")
		buf.WriteString("Timeout unit: `" + c.Timeout.Unit + "`. Matcher syntax: `" + c.Matcher.Syntax + "`")
		if c.Matcher.Anchor {
			buf.WriteString(" (output anchored)")
		}
		if c.Matcher.ExactLists {
			buf.WriteString(" (exact `|`/`,` lists)")
		}
		buf.WriteString(".")
		if c.RepositoryBase != nil {
			base := ""
			switch {
			case c.RepositoryBase.Env != "":
				base = "env `" + c.RepositoryBase.Env + "`"
			case c.RepositoryBase.Shell != "":
				base = "shell `" + c.RepositoryBase.Shell + "`"
			case c.RepositoryBase.Cwd != "":
				base = "cwd `" + c.RepositoryBase.Cwd + "`"
			}
			buf.WriteString(" Repository base: " + base + ".")
		}
		if len(c.LoadsHooksOf) != 0 {
			buf.WriteString(" Also loads hooks of: " + joinOr(c.LoadsHooksOf, "") + ".")
		}
		buf.WriteString("\n\n")

		if len(c.Env) != 0 || len(c.PluginEnv) != 0 {
			rows := [][]string{}
			for _, concept := range sortedKeys(c.Env) {
				v := c.Env[concept]
				rows = append(rows, []string{"`" + concept + "`", joinOr(v.Names, "-"), joinOr(v.Events, "all")})
			}
			for _, concept := range sortedKeys(c.PluginEnv) {
				v := c.PluginEnv[concept]
				rows = append(rows, []string{"`" + concept + "` (plugin only)", joinOr(v.Names, "-"), joinOr(v.Events, "all")})
			}
			table(&buf, []string{"Variable concept", "Names", "Events"}, rows)
		}

		rows := [][]string{}
		for _, name := range sortedKeys(c.Events) {
			e := c.Events[name]
			canonical := e.Canonical
			if canonical == "" {
				canonical = "(native only)"
			}
			matcher := e.Matcher
			if e.MCP {
				matcher += " (mcp)"
			}
			if len(e.Tools) != 0 {
				matcher += " [" + strings.Join(e.Tools, ", ") + "]"
			}
			timeout := "-"
			if e.Timeout != nil {
				timeout = fmt.Sprintf("%d-%d", e.Timeout.Min, e.Timeout.Max)
			}
			rows = append(rows, []string{
				"`" + name + "`", canonical, matcher, joinOr(e.Types, "-"), timeout,
			})
		}
		table(&buf, []string{"Event", "Canonical", "Matcher", "Types", "Timeout bounds"}, rows)
	}
	return buf.Bytes(), nil
}

// checkFresh reports whether the document at path matches the freshly
// generated reference. It is the same comparison the -check mode runs, shared
// so tests exercise the real gate instead of duplicating it.
func checkFresh(generated []byte, path string) error {
	current, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(current, generated) {
		return fmt.Errorf("stale generated reference %s: run make catalog-docs", path)
	}
	return nil
}

func main() {
	check := flag.Bool("check", false, "verify the committed document is current instead of writing it")
	flag.Parse()
	doc, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "catalog-docs:", err)
		os.Exit(1)
	}
	if *check {
		if err := checkFresh(doc, docPath); err != nil {
			fmt.Fprintln(os.Stderr, "catalog-docs:", err)
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(docPath), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "catalog-docs:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(docPath, doc, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "catalog-docs:", err)
		os.Exit(1)
	}
}
